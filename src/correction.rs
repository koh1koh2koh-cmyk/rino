/// الحد الأدنى لطول الكلمة المطلوب للتصحيح التلقائي.
/// الكلمات الأقصر من هذا تُعدّ أسماء متغيرات محتملة ولا تُصحّح.
const MIN_LEN_FOR_CORRECTION: usize = 4;

pub fn suggest_keyword(input: &str) -> Option<&'static str> {
    if PROTECTED.contains(&input) {
        return None;
    }

    let input_len = input.chars().count();

    // لا نصحّح الكلمات القصيرة — قد تكون أسماء متغيرات
    if input_len < MIN_LEN_FOR_CORRECTION {
        return None;
    }

    let mut best: Option<(&'static str, usize)> = None;
    for &kw in KEYWORDS {
        // لا نقترح كلمات مفتاحية قصيرة (تعارض محتمل مع الأسماء)
        if kw.chars().count() < MIN_LEN_FOR_CORRECTION {
            continue;
        }

        let dist = levenshtein(input, kw);
        if dist <= 1 {
            match best {
                Some((_, d)) if d <= dist => {}
                _ => best = Some((kw, dist)),
            }
        }
    }
    best.map(|(k, _)| k)
}