pub fn suggest_keyword(input: &str) -> Option<&'static str> {
    // لا تصحح الكلمات المحمية
    if PROTECTED.contains(&input) {
        return None;
    }

    // لا تصحح الكلمات القصيرة جدًا (< 3 أحرف)
    if input.chars().count() < 3 {
        return None;
    }

    let mut best: Option<(&'static str, usize)> = None;
    for &kw in KEYWORDS {
        // تجاهل الكلمات المفتاحية القصيرة جدًا
        if kw.chars().count() < 3 {
            continue;
        }
        let dist = levenshtein(input, kw);
        if dist <= 1 {
            match best {
                Some((_, d)) if d <= dist => {}
                _ => best = Some((kw, dist)),
            }
        }
    }
    best.map(|(k, _)| k)
}